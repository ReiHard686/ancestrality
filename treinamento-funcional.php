                    <h4 id="item-2" class="habito-titulo pb-2 mb-3">O Levantamento Terra </h4>
                    <p class="text-start">
                        Levantar um peso morto do chão é, possivelmente, o gesto mais arcaico da história humana.
                        Os gregos antigos já praticavam variações deste movimento com pedras, e cada civilização caçadora-recolectora dependia dele para erguer a caça abatida,
                        transportar lenha ou mover rochas para construir abrigo.
                        O levantamento terra é o mestre dos exercícios funcionais: ativa simultaneamente a lombar, o glúteo, o posterior da coxa, o core e a pegada.
                        Um adulto incapaz de levantar com segurança o seu próprio peso do chão é um adulto biologicamente vulnerável —
                        incapaz de auxiliar a família numa emergência ou de carregar um filho ao colo sem se lesionar.

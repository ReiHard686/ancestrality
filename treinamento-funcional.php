                <article class="habito-bloco habito-4 py-4">
                    <h5 class="habito-label text-uppercase"> O Padrão da Trepa e da Fuga </h5>
                    <h4 id="item-4" class="habito-titulo pb-2 mb-3">A Barra Fixa </h4>
                    <p class="text-start">
                        A capacidade de içar o próprio peso corporal foi, durante centenas de milhares de anos, a diferença entre sobreviver e ser devorado.
                        Os nossos antepassados trepavam árvores para escapar de predadores, colher frutos, vigiar o território e proteger a prole.
                        A barra fixa é a tradução direta deste padrão e desenvolve a largura dos dorsais, a força do bíceps, a estabilidade do ombro e — fundamentalmente — uma postura ereta e dominante.
                        Num mundo onde 90% da população masculina não consegue executar 10 repetições limpas, dominar este movimento é, por si só, um regresso à condição plena de adulto funcional.
                    </p>
                    <div class="card-group card-grupo-ancestral gap-3">
                        <div class="card">
                            <div class="card-body p-3">
                                <div class="d-flex align-items-center gap-2 mb-2">
                                    <i class="bi bi-list-ol card-icon"></i>
                                    <h5 class="card-title mb-0">Como executar</h5>
                                </div>
                                <ol class="card-text mb-0 ps-3">
                                    <li>Passo: Suspenda-se na barra com pegada pronada (palmas para a frente), ligeiramente mais larga que a largura dos ombros.</li>
                                    <li>Passo: Contraia os omoplatas para baixo antes de iniciar a puxada (este detalhe protege o ombro e ativa corretamente o dorsal). </li>
                                    <li>Passo: Puxe o corpo para cima até que o queixo ultrapasse a barra, sem balançar nem dar impulso com as pernas.</li>
                                    <li>Passo: Desça com controlo até à extensão total dos braços. </li>
                                </ol>
                            </div>

                                </div>
                                <ol class="card-text mb-0 ps-3">
                                    <li> 
                                        Passo: Segure um halter pesado em cada mão (comece com cerca de 25% do seu peso corporal por mão e progrida gradualmente). 
                                    </li>
                                    <li>Passo: Mantenha os ombros para trás e para baixo, o peito aberto, o core contraído e o olhar à frente. </li>
                                    <li>Passo: Inspire, contraia o core e levante empurrando o chão com os calcanhares, mantendo a barra colada ao corpo durante toda a subida. </li>
                                    <li>Passo: Caminhe com passos firmes e curtos, sem balançar, durante 30 a 60 metros ou até que a pegada falhe. </li>
                                    <li>Passo: Recupere e repita por 3 a 5 séries. </li>
                                </ol>

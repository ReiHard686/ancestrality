                    <h5 class="habito-label text-uppercase"> O Padrão da Escalada e da Defesa</h5>
                    <h4 id="item-5" class="habito-titulo pb-2 mb-3">As Paralelas</h4>
                    <p class="text-start">
                        O movimento de empurrar o próprio corpo para cima sobre dois apoios replica o gesto de subir um muro de pedra, transpor um tronco caído, içar-se sobre uma rocha à beira de um precipício ou afastar um adversário em combate corpo-a-corpo.
                        As paralelas são o complemento perfeito da barra fixa: enquanto esta desenvolve a tração, aquelas desenvolvem a empurrada vertical — o padrão que constrói peitoral inferior, tríceps e ombro anterior de forma equilibrada e proporcional,
                        sem o aspeto artificial que se observa em fisiculturistas profissionais.
                        Trata-se de um exercício de emergência funcional: num desabamento, num acidente ou numa fuga, é a sua força de paralelas que o pode salvar.
                    </p>
                    <div class="card-group card-grupo-ancestral gap-3">
                        <div class="card">
                            <div class="card-body p-3">
                                <div class="d-flex align-items-center gap-2 mb-2">
                                    <i class="bi bi-list-ol card-icon"></i>
                                    <h5 class="card-title mb-0">Como executar</h5>
                                </div>
                                <ol class="card-text mb-0 ps-3">
                                    <li>
                                        Passo: Apoie-se em duas barras paralelas com os braços estendidos, ombros ligeiramente projetados para a frente e tronco levemente inclinado para focar o peitoral (ou completamente vertical para enfatizar o tríceps). 
                                    </li>
                                    <li>
                                        Passo: Desça flexionando os cotovelos até que os ombros fiquem ligeiramente abaixo da linha dos cotovelos, sem cair em colapso.
                                    </li>
                                    <li>
                                        Passo: Suba pressionando as barras, contraindo o peitoral e o tríceps até à extensão completa, sem travar o cotovelo. 
                                    </li>
                                    <li>
                                        Passo: Quem ainda não tem força suficiente deve começar com paralelas assistidas por banda elástica ou pela versão estática (apoio isométrico no topo).
                                    </li>
                                </ol>
